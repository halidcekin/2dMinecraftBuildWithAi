export const DEFAULT_BLOCK = 'stone';

export function resolveBlock(id) {
  const key = String(id ?? '').trim().toLowerCase().replace(/^minecraft:/, '');
  if (key === 'air') return 'air';
  if (BLOCKS[key]) return key;
  console.warn?.(`Bilinmeyen blok "${id}", ${DEFAULT_BLOCK} kullanıldı`);
  return DEFAULT_BLOCK;
}
